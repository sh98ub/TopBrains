CREATE TABLE ZIPCODE_INFO(
ZIP_CODE VARCHAR(5),
CITY VARCHAR(25),
STATE VARCHAR(2)
);

CREATE TABLE INSTRUCTOR_INFO(
INSTRUCTOR_ID INT,
INSTRUCTOR_FIRST_NAME VARCHAR(25),
INSTRUCTOR_LAST_NAME VARCHAR(25),
STREET_ADDRESS VARCHAR(50),
ZIP_CODE VARCHAR(5)
);

CREATE TABLE COURSE_INFO(
COURSE_NO INT,
COURSE_NAME VARCHAR(50),
COURSE_PREREQUISITE INT,
COST DECIMAL(9,2)
);

CREATE TABLE STUDENT_INFO(
STUDENT_ID INT,
STUDENT_FIRST_NAME VARCHAR(25),
STUDENT_LAST_NAME VARCHAR(25),
STREET_ADDRESS VARCHAR(50),
ZIP_CODE VARCHAR(5)
);

CREATE TABLE SECTION_INFO(
SECTION_ID INT,
COURSE_NO INT,
SECTION_NO INT,
INSTRUCTOR_ID INT,
LOCATION VARCHAR(50),
CAPACITY INT
);

CREATE TABLE ENROLLMENT_INFO(
STUDENT_ID INT,
SECTION_ID INT,
ENROLLMENT_DATE DATE
);

CREATE TABLE GRADE_INFO(
STUDENT_ID INT,
SECTION_ID INT,
GRADE_TYPE_CODE CHAR(2),
GRADE_CODE_OCCURANCE INT,
NUMERIC_GRADE INT
);

