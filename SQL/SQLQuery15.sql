SELECT S.STUDENT_ID,S.STUDENT_FIRST_NAME+' '+S.STUDENT_LAST_NAME AS NAME
FROM STUDENT_INFO S
JOIN ENROLLMENT_INFO E ON S.STUDENT_ID=E.STUDENT_ID
WHERE MONTH(E.ENROLLMENT_DATE)=1 AND YEAR(E.ENROLLMENT_DATE)=1999
ORDER BY NAME;

